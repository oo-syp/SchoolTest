def _bd_score(ans, res):
    raw = {}
    for k in BD_ORDER:
        name, yes, no, coef, tab = BD_KEY[k]
        v = sum(1 for q in yes if ans.get(q) == "y") + sum(1 for q in no if ans.get(q) == "n")
        std = v * coef
        sten = _lvl(BD_STEN_A if tab == "A" else BD_STEN_B, std)
        raw[k] = (v, std, sten)
        res["scales"].append({"id": k, "name": name, "value": v, "min": 0, "max": len(yes) + len(no),
                              "std": std, "sten": sten,
                              "level": "%s (%d стандартных баллов, %d стен)" % (_lvl(BD_STEN_LEVEL, sten), std, sten)})
    agr_std = (raw["fiz"][1] + raw["razdr"][1] + raw["verb"][1]) / 3.0
    hos_std = (raw["obida"][1] + raw["podozr"][1]) / 2.0
    agr_raw = raw["fiz"][0] + raw["razdr"][0] + raw["verb"][0]
    hos_raw = raw["obida"][0] + raw["podozr"][0]
    agr_sten, hos_sten = _lvl(BD_STEN_AGR, agr_std), _lvl(BD_STEN_B, hos_std)
    res["indices"] = [
        {"id": "agr", "name": "Индекс агрессивности", "raw": agr_raw, "std": round(agr_std, 1), "sten": agr_sten,
         "level": _lvl(BD_STEN_LEVEL, agr_sten), "norm": "по Е. И. Рогову норма сырого балла 21 ± 4"},
        {"id": "hos", "name": "Индекс враждебности", "raw": hos_raw, "std": round(hos_std, 1), "sten": hos_sten,
         "level": _lvl(BD_STEN_LEVEL, hos_sten), "norm": "по Е. И. Рогову норма сырого балла 6,5–7 ± 3"},
    ]
    res["summary"] = "Агрессивность — %s (%d сырых баллов, %d стен); враждебность — %s (%d сырых баллов, %d стен)" % (
        _lvl(BD_STEN_LEVEL, agr_sten), agr_raw, agr_sten, _lvl(BD_STEN_LEVEL, hos_sten), hos_raw, hos_sten)
    high = [s for s in res["scales"] if s["sten"] >= 7]
    res["top"] = [s["id"] for s in high]
    for s in high:
        res["text"].append({"title": "%s: %s" % (s["name"], _lvl(BD_STEN_LEVEL, s["sten"])), "body": BD_TEXT[s["id"]]})
    res["text"].append({"title": "Как читать результат", "body":
        "За каждое совпадение с ключом начисляется 1 сырой балл. Чтобы шкалы можно было сравнивать между собой, "
        "сырой балл умножается на коэффициент шкалы — так максимум каждой шкалы приводится к 100 баллам, — "
        "а затем переводится в стены: 1–2 стена — низкий уровень, 3–4 — средний, 5–6 — повышенный, 7 — высокий, "
        "8 и выше — очень высокий. Индекс агрессивности — среднее по шкалам физической, вербальной агрессии и "
        "раздражения, индекс враждебности — среднее по шкалам обиды и подозрительности (А. А. Хван с соавт.). "
        "Агрессивность как свойство личности следует оценивать вместе с другими методиками и беседой."})
    res["chart"] = "bars"
    if agr_sten >= 8 or hos_sten >= 8:
        res["warnings"].append("Очень высокий уровень по индексу: рекомендуется индивидуальная беседа и "
                               "уточнение результата другими методиками.")


