def values(res):
    mid = res.get("method")
    if mid == "phillips":
        return [res.get("total_percent")] + [s["percent"] for s in res.get("scales") or []]
    if mid == "lusk":
        return [res.get("total"), (res.get("scales") or [{}])[0].get("level", "")]
    if mid == "stai":
        sc = res.get("scales") or []
        return [sc[0]["value"] if sc else "", sc[1]["value"] if len(sc) > 1 else ""]
    return [s["value"] for s in res.get("scales") or []]


def short(res):
    mid = res.get("method")
    if mid == "phillips":
        return ["%s%%" % res.get("total_percent")]
    if mid == "lusk":
        return [str(res.get("total"))]
    if mid == "stai":
        sc = res.get("scales") or []
        return ["СТ %s / ЛТ %s" % (sc[0]["value"] if sc else "", sc[1]["value"] if len(sc) > 1 else "")]
    return [str(s["value"]) for s in res.get("scales") or []]


def summary(mid, results):
    out, n = [], len(results)
    if not n:
        return out
    if mid == "phillips":
        vals = [r.get("total_percent", 0) for r in results]
        out.append({"name": "Общая тревожность, % несовпадений", "avg": round(sum(vals) / float(n), 1), "max": 100})
        for lvl in ("повышенная тревожность", "высокая тревожность"):
            out.append({"name": lvl, "count": sum(1 for r in results if r.get("total_level") == lvl)})
        for fid in PHIL_ORDER:
            name, _ = PHIL_FACTORS[fid]
            vals = [s["percent"] for r in results for s in r.get("scales") or [] if s["id"] == fid]
            if vals:
                out.append({"name": name, "avg": round(sum(vals) / float(len(vals)), 1), "max": 100})
    elif mid == "lusk":
        vals = [r.get("total", 0) for r in results]
        out.append({"name": "Уровень школьной мотивации, балл", "avg": round(sum(vals) / float(n), 1), "max": 30})
        for lvl, name, _ in [l[1:] for l in LUSK_LEVELS]:
            out.append({"name": name, "count": sum(1 for r in results if r.get("level") == lvl)})
    elif mid == "stai":
        for idx, label in ((0, "Ситуативная тревожность"), (1, "Личностная тревожность")):
            vals = [r["scales"][idx]["value"] for r in results if len(r.get("scales") or []) > idx]
            if vals:
                out.append({"name": label, "avg": round(sum(vals) / float(len(vals)), 1), "max": 80, "min": 20})
                out.append({"name": label + " — высокая тревожность", "count": sum(
                    1 for r in results if len(r.get("scales") or []) > idx and r["scales"][idx]["level"] == "высокая тревожность")})
    return out


