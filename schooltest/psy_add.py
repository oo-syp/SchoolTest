def _phil_mismatch(i, ans):
    a = ans.get(i)
    if a is None:
        return None
    expected = "y" if i in PHIL_PLUS else "n"
    return a != expected


def _phil_score(ans, res):
    total_mism, total_n = 0, 0
    for i in range(1, 59):
        m = _phil_mismatch(i, ans)
        if m is not None:
            total_n += 1
            if m:
                total_mism += 1
    pct = round(100.0 * total_mism / total_n, 1) if total_n else 0
    res["total_mismatch"] = total_mism
    res["total_percent"] = pct
    res["total_level"] = _lvl(PHIL_LEVEL_TABLE, pct)
    for fid in PHIL_ORDER:
        name, nums = PHIL_FACTORS[fid]
        mism, n = 0, 0
        for i in nums:
            m = _phil_mismatch(i, ans)
            if m is not None:
                n += 1
                if m:
                    mism += 1
        fpct = round(100.0 * mism / n, 1) if n else 0
        res["scales"].append({"id": fid, "name": name, "value": mism, "min": 0, "max": n,
                               "percent": fpct, "level": _lvl(PHIL_LEVEL_TABLE, fpct)})
    res["summary"] = "Общая тревожность: %s (%s%% несовпадений с ключом)" % (res["total_level"], res["total_percent"])
    high = [s["name"] for s in res["scales"] if s["level"] != "норма"]
    if high:
        res["text"].append({"title": "Факторы с повышенной или высокой тревожностью", "body": "; ".join(high) + "."})
    res["text"].append({"title": "Как читать результат", "body":
                        "Несовпадение ответа с ключом — проявление тревожности. Для общего показателя и для каждого "
                        "из 8 факторов доля несовпадений до 50% — норма, от 50 до 75% — повышенная тревожность, "
                        "свыше 75% — высокая тревожность."})
    res["chart"] = "bars"


