def questions(mid):
    if mid == "phillips":
        return [{"text": t, "options": YES_NO} for t in PHIL_Q]
    if mid == "lusk":
        return [{"text": t, "options": [{"id": str(i + 1), "text": opt} for i, opt in enumerate(opts)]}
                for t, opts in LUSK_Q]
    if mid == "stai":
        qs = [{"text": t, "options": STAI_OPTIONS, "section": "state"} for t in STAI_STATE_Q]
        qs += [{"text": t, "options": STAI_OPTIONS, "section": "trait"} for t in STAI_TRAIT_Q]
        return qs
    return []


def score(mid, ans, extra, res, settings=None):
    if mid == "phillips":
        _phil_score(ans, res)
    elif mid == "lusk":
        _lusk_score(ans, res)
    elif mid == "stai":
        _stai_score(ans, res)
    return res


def headers(mid):
    if mid == "phillips":
        return ["Общ.,%"] + [PHIL_SHORT[fid] for fid in PHIL_ORDER]
    if mid == "lusk":
        return ["Балл", "Уровень"]
    if mid == "stai":
        return ["СТ", "ЛТ"]
