METHOD_ORDER = ["ddo", "kos", "epi", "ki144"]


def questions(mid):
    """Вопросы методики в формате снимка теста (тип psy)."""
    qs = []
    if mid == "ddo":
        for i, (a, b) in enumerate(DDO_PAIRS, 1):
            qs.append({"text": "Что бы Вы предпочли?", "options": [{"id": "a", "text": a}, {"id": "b", "text": b}]})
    elif mid == "kos":
        qs = [{"text": t, "options": YES_NO} for t in KOS_Q]
    elif mid == "epi":
        qs = [{"text": t, "options": YES_NO} for t in EPI_Q]
    elif mid == "ki144":
        qs = [{"text": "Хотелось бы Вам? Нравится ли Вам? " + t, "options": KI_OPTIONS} for t in KI_Q]
    return qs


def snapshot(mid, settings=None):
    m = METHODS[mid]
    st = {"shuffle_questions": False, "shuffle_options": False, "time_limit": 0, "free_nav": True,
          "show_result": (settings or {}).get("show_result") or m["show_default"], "no_copy": False, "track_focus": False,
          "variants": 1, "scale": {"mode": "percent"}, "psy": mid, "ask": m["ask"]}
    qs = []
    for i, q in enumerate(questions(mid), 1):
        qs.append({"id": str(i), "task_id": 0, "task_num": 1, "variant": 0, "type": "psy",
                   "body": {"text": q["text"], "options": q["options"], "num": i}, "answer": {}, "points": 0})
    return {"test": {"id": None, "title": m["name"], "subject": "Психодиагностика", "grade": None, "settings": st},
            "tasks": [{"id": 0, "num": 1, "title": "", "level": None, "pick": 0}], "questions": qs, "psy": mid}


def _answers(snap_answers):
    """{номер вопроса: id ответа}"""
    out = {}
    for qid, resp in snap_answers.items():
        if isinstance(resp, dict) and resp.get("choice") not in (None, ""):
            try:
                out[int(qid)] = str(resp["choice"])
            except ValueError:
                pass
    return out


def score(mid, answers, extra=None):
    """answers — {qid: response}. Возвращает результат методики."""
    ans = _answers(answers)
    extra = extra or {}
    n = METHODS[mid]["count"]
    res = {"method": mid, "answered": len(ans), "total": n, "scales": [], "text": [], "warnings": []}
    if len(ans) < n:
        res["warnings"].append("Ответы даны не на все вопросы (%d из %d)." % (len(ans), n))
    if mid == "ddo":
        for k in DDO_ORDER:
            name, keys = DDO_KEY[k]
            v = 0
            for item in keys.split():
                num, side = int(item[:-1]), item[-1]
                if ans.get(num) == side:
                    v += 1
            lvl = "ярко выражена" if v >= 7 else ("средне выражена" if v >= 3 else "не выражена")
            res["scales"].append({"id": k, "name": name, "value": v, "min": 0, "max": 8, "level": lvl})
        top = max(s["value"] for s in res["scales"])
        best = [s for s in res["scales"] if s["value"] == top and top > 0]
        res["summary"] = "Преобладающий тип: " + ", ".join("«%s»" % s["name"] for s in best) if best else "Склонности не выявлены"
        res["top"] = [s["id"] for s in best]
        for s in best:
            res["text"].append({"title": s["name"], "body": DDO_TEXT[s["id"]]})
        res["text"].append({"title": "Как читать результат", "body": "Рекомендуется обратить внимание на тип профессий, "
                            "получивший наибольшее количество баллов (из 8). 0–2 балла — склонность не выражена, "
                            "3–6 — средне выражена, 7–8 — ярко выражена."})
        res["chart"] = "bars"
    elif mid == "kos":
        parts = []
        for k in ("comm", "org"):
            name, yes, no, table = KOS_KEY[k]
            c = sum(1 for q in yes if ans.get(q) == "y") + sum(1 for q in no if ans.get(q) == "n")
            kk = round(0.05 * c, 2)
            mark = 5
            for hi, m in table:
                if kk <= hi + 1e-9:
                    mark = m
                    break
            res["scales"].append({"id": k, "name": name, "value": c, "min": 0, "max": 20, "coef": kk, "mark": mark,
                                  "level": "%s (оценка %d, К = %s)" % (KOS_LEVELS[mark], mark, str(kk).replace(".", ","))})
            parts.append("%s — %s" % (name.split()[0].lower(), KOS_LEVELS[mark]))
            res["text"].append({"title": name + ": " + KOS_LEVELS[mark], "body": KOS_TEXT[mark]})
        res["summary"] = "; ".join(parts)
        res["text"].append({"title": "Как читать результат", "body": "Оценочный коэффициент К = 0,05 × число ответов, "
                            "совпавших с ключом (от 0 до 1). Методика констатирует уровень развития склонностей в данный "
                            "период; при положительной мотивации и надлежащих условиях они могут развиваться."})
        res["chart"] = "bars"
    elif mid == "epi":
        vals = {}
        for k in ("E", "N", "L"):
            name, yes, no = EPI_KEY[k]
            v = sum(1 for q in yes if ans.get(q) == "y") + sum(1 for q in no if ans.get(q) == "n")
            vals[k] = v
        e, nn, l = vals["E"], vals["N"], vals["L"]
        e_lvl = ("выраженный интроверт" if e <= 7 else "интроверт" if e <= 11 else "экстраверт" if e <= 18 else "выраженный экстраверт")
        n_lvl = ("высокая эмоциональная стабильность" if nn <= 10 else "средняя эмоциональная стабильность" if nn <= 14 else
                 "высокая эмоциональная нестабильность" if nn <= 18 else "очень высокая эмоциональная нестабильность")
        l_lvl = "результат достоверен" if l <= 3 else ("критический показатель" if l <= 5 else "результат недостоверен")
        res["scales"] = [
            {"id": "E", "name": EPI_KEY["E"][0], "value": e, "min": 0, "max": len(EPI_KEY["E"][1]) + len(EPI_KEY["E"][2]), "level": e_lvl},
            {"id": "N", "name": EPI_KEY["N"][0], "value": nn, "min": 0, "max": len(EPI_KEY["N"][1]), "level": n_lvl},
            {"id": "L", "name": EPI_KEY["L"][0], "value": l, "min": 0, "max": len(EPI_KEY["L"][1]) + len(EPI_KEY["L"][2]), "level": l_lvl},
        ]
        if e >= 12:
            tk = "choleric" if nn >= 12 else "sanguine"
        else:
            tk = "melancholic" if nn >= 12 else "phlegmatic"
        res["temperament"] = tk
        res["summary"] = "Тип темперамента: %s (Э = %d, Н = %d, Л = %d)" % (EPI_TEMPER[tk][0].lower(), e, nn, l)
        if l > 5:
            res["warnings"].append("Показатель шкалы лжи выше 5: ответы ориентированы на хорошее впечатление о себе, "
                                   "результаты следует считать недостоверными.")
        elif l >= 4:
            res["warnings"].append("Показатель шкалы лжи 4–5 — критический: возможна тенденция давать «хорошие» ответы.")
        res["text"].append({"title": EPI_TEMPER[tk][0], "body": EPI_TEMPER[tk][1]})
        res["text"].append({"title": "Экстраверсия — интроверсия: " + e_lvl, "body":
                            "Экстраверта характеризуют общительность, широкий круг знакомств, импульсивность, оптимистичность. "
                            "Интроверт спокоен, сдержан, склонен к самоанализу, заранее планирует свои действия. "
                            "Шкала: 0–7 — выраженный интроверт, 8–11 — интроверт, 12–18 — экстраверт, 19 и выше — выраженный экстраверт."})
        res["text"].append({"title": "Нейротизм: " + n_lvl, "body":
                            "Нейротизм характеризует эмоциональную устойчивость или неустойчивость. До 10 баллов — высокая "
                            "стабильность, 11–14 — средняя, 15–18 — высокая нестабильность, 19 и выше — очень высокая."})
        g = extra.get("gender")
        try:
            age = int(extra.get("age") or 0)
        except ValueError:
            age = 0
        norm = EPI_NORMS.get((max(10, min(15, age)), g)) if age and g in ("m", "f") else None
        if norm:
            res["norm"] = {"age": age, "gender": g, "L": norm[0:2], "E": norm[2:4], "N": norm[4:6]}
            def cmp(v, lo, hi):
                return "в пределах нормы" if lo <= v <= hi else ("ниже нормы" if v < lo else "выше нормы")
            res["text"].append({"title": "Сравнение с нормативами (%d лет, %s)" % (age, "юноши" if g == "m" else "девушки"),
                                "body": "Экстраверсия %d — %s (%d–%d); нейротизм %d — %s (%d–%d); шкала лжи %d — %s (%d–%d)." %
                                (e, cmp(e, *norm[2:4]), norm[2], norm[3], nn, cmp(nn, *norm[4:6]), norm[4], norm[5],
                                 l, cmp(l, *norm[0:2]), norm[0], norm[1])})
        res["chart"] = "eysenck"
    elif mid == "ki144":
        for i, name in enumerate(KI_SPHERES, 1):
            v = 0
            for j in range(6):
                try:
                    v += int(ans.get(i + 24 * j, "0"))
                except ValueError:
                    pass
            res["scales"].append({"id": "s%d" % i, "name": name, "value": v, "min": -12, "max": 12, "level": _ki_level(v)})
        order = sorted(res["scales"], key=lambda s: -s["value"])
        top = [s for s in order if s["value"] >= 5][:5]
        res["top"] = [s["id"] for s in top]
        res["summary"] = ("Выраженные интересы: " + ", ".join("%s (%+d)" % (s["name"], s["value"]) for s in top)) if top else \
            "Выраженных интересов не выявлено"
        neg = [s for s in order if s["value"] <= -6]
        if neg:
            res["text"].append({"title": "Отвергаемые сферы", "body": ", ".join(s["name"] for s in neg)})
        res["text"].append({"title": "Как читать результат", "body": "Сумма по каждой сфере от −12 до +12: от −12 до −6 — "
                            "область деятельности активно отрицается; от −5 до −1 — интереса не вызывает; от +1 до +4 — "
                            "интерес выражен слабо; от +5 до +7 — выраженный интерес; от +8 до +12 — ярко выраженный интерес. "
                            "Заключение об интересах следует уточнить в индивидуальной беседе."})
        res["chart"] = "bars"
    return res


def short_cells(res):
    """Краткие значения для таблицы результатов группы."""
    mid = res.get("method")
    if mid == "ddo":
        return ["%s %d" % (DDO_KEY[s["id"]][0].split("— ")[1][:6], s["value"]) for s in res["scales"]]
    if mid == "kos":
        return ["К %s (%d)" % (str(s["coef"]).replace(".", ","), s["mark"]) for s in res["scales"]]
    if mid == "epi":
        return ["%d" % s["value"] for s in res["scales"]] + [EPI_TEMPER.get(res.get("temperament"), ("",))[0]]
    return []


